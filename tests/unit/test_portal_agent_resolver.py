"""How the Portal agent resolves names without reaching the LAN.

Normally through public resolvers, in its own resolv.conf; only when public
DNS doesn't answer from this host, through the host's resolver, allowed in a
drop-in (which then gives the agent that LAN address on every port).
"""

from __future__ import annotations

import time
from pathlib import Path

import pytest

from sp_rtk_base.portal_agent.resolver import (
    PUBLIC_RESOLVERS,
    answers,
    main,
    plan,
)
from tests.fixtures.fake_dns import FakeDns, closed_port

LAN_HOST = "# generated by NetworkManager\nsearch lan\nnameserver 192.168.0.1\n"


def _allowed(drop_in: str) -> list[str]:
    return [
        ln.removeprefix("IPAddressAllow=")
        for ln in drop_in.splitlines()
        if ln.startswith("IPAddressAllow=")
    ]


def _nameservers(resolv_conf: str) -> list[str]:
    return [
        ln.split()[1] for ln in resolv_conf.splitlines() if ln.startswith("nameserver ")
    ]


class TestPublicDnsAnswers:
    def test_the_agent_gets_the_public_resolvers_and_no_lan_allowance(self) -> None:
        p = plan(LAN_HOST, answering=["1.1.1.1", "9.9.9.9", "8.8.8.8"])

        assert p.resolv_conf is not None
        assert _nameservers(p.resolv_conf) == ["1.1.1.1", "9.9.9.9", "8.8.8.8"]
        assert "search" not in p.resolv_conf
        assert p.drop_in is None
        assert not p.warn
        assert "1.1.1.1" in p.message

    def test_lists_only_the_ones_that_answered(self) -> None:
        p = plan(LAN_HOST, answering=["9.9.9.9"])

        assert p.resolv_conf is not None
        assert _nameservers(p.resolv_conf) == ["9.9.9.9"]
        assert p.drop_in is None

    def test_the_public_resolvers_are_ipv4(self) -> None:
        assert PUBLIC_RESOLVERS
        assert all(":" not in r for r in PUBLIC_RESOLVERS)


class TestPublicDnsBlocked:
    @pytest.mark.parametrize(
        ("host", "allowed"),
        [
            ("nameserver 192.168.0.1\n", "192.168.0.1"),
            ("nameserver 172.20.0.1\nnameserver 172.32.0.1\n", "172.20.0.1"),
            ("nameserver 169.254.1.1\n", "169.254.1.1"),
            ("nameserver 10.0.0.1\nnameserver 10.0.0.1\n", "10.0.0.1"),
            # An IPv6 resolver is no use to an agent without IPv6 sockets.
            ("nameserver fd00::53\nnameserver 10.0.0.1\n", "10.0.0.1"),
        ],
    )
    def test_falls_back_to_the_lan_resolver_with_a_warning(
        self, host: str, allowed: str
    ) -> None:
        p = plan(host, answering=[])

        assert p.resolv_conf is None
        assert p.drop_in is not None
        assert "[Service]\n" in p.drop_in
        # Clears the unit's bind mount: the agent reads the host's resolv.conf.
        assert "\nBindReadOnlyPaths=\n" in p.drop_in
        assert _allowed(p.drop_in) == [allowed]
        assert p.warn
        assert allowed in p.message
        assert "any port" in p.message

    @pytest.mark.parametrize("host", ["nameserver 127.0.0.53\n", "nameserver ::1\n"])
    def test_a_loopback_resolver_needs_no_lan_allowance(self, host: str) -> None:
        p = plan(host, answering=[])

        assert p.drop_in is not None
        assert "\nBindReadOnlyPaths=\n" in p.drop_in
        assert _allowed(p.drop_in) == []
        assert p.warn
        assert "any port" not in p.message

    @pytest.mark.parametrize(
        "host", ["", "# nameserver 10.0.0.9\nnameserver\nnameserver bogus\n"]
    )
    def test_warns_when_the_agent_is_left_with_no_resolver(self, host: str) -> None:
        p = plan(host, answering=[])

        assert p.warn
        assert "can't resolve" in p.message

    def test_an_ipv6_only_lan_resolver_leaves_the_agent_without_dns(self) -> None:
        p = plan("nameserver fd00::53\n", answering=[])

        assert p.drop_in is not None
        assert _allowed(p.drop_in) == []
        assert "can't resolve" in p.message


class TestAnswers:
    def test_a_resolver_that_answers(self) -> None:
        with FakeDns("ok") as dns:
            assert answers(dns.server, timeout=1)
            assert dns.queries == 1

    @pytest.mark.parametrize("reply", ["refused", "wrong-id"])
    def test_a_reply_that_isnt_an_answer(self, reply: str) -> None:
        with FakeDns(reply) as dns:
            assert not answers(dns.server, timeout=0.3)

    def test_a_silent_resolver_times_out(self) -> None:
        with FakeDns("silent") as dns:
            started = time.monotonic()
            assert not answers(dns.server, timeout=0.3)
            assert time.monotonic() - started < 1

    def test_a_refused_port(self) -> None:
        started = time.monotonic()
        assert not answers(closed_port(), timeout=2)
        assert time.monotonic() - started < 1


class TestMain:
    """What install.sh runs: checks public DNS, then writes the agent's
    resolv.conf or the fallback drop-in, removing whichever is stale."""

    @pytest.fixture()
    def paths(self, tmp_path: Path) -> dict[str, Path]:
        host = tmp_path / "resolv.conf"
        host.write_text(LAN_HOST)
        return {
            "host": host,
            "agent": tmp_path / "etc" / "portal-agent-resolv.conf",
            "drop_in": tmp_path / "unit.d" / "resolver.conf",
        }

    def _main(self, paths: dict[str, Path], public: list[str]) -> int:
        return main(
            [
                "--host-resolv-conf",
                str(paths["host"]),
                "--agent-resolv-conf",
                str(paths["agent"]),
                "--drop-in",
                str(paths["drop_in"]),
                "--public",
                " ".join(public),
                "--timeout",
                "0.3",
            ]
        )

    def test_public_dns_answers(
        self, paths: dict[str, Path], capsys: pytest.CaptureFixture[str]
    ) -> None:
        with FakeDns() as dns:
            assert self._main(paths, [closed_port(), dns.server]) == 0

        assert _nameservers(paths["agent"].read_text()) == ["127.0.0.1"]
        assert paths["agent"].stat().st_mode & 0o777 == 0o644
        assert not paths["drop_in"].exists()
        assert "127.0.0.1" in capsys.readouterr().out

    def test_public_dns_blocked(
        self, paths: dict[str, Path], capsys: pytest.CaptureFixture[str]
    ) -> None:
        assert self._main(paths, [closed_port()]) == 3

        assert _allowed(paths["drop_in"].read_text()) == ["192.168.0.1"]
        assert paths["drop_in"].stat().st_mode & 0o777 == 0o644
        assert not paths["agent"].exists()
        assert "192.168.0.1" in capsys.readouterr().out

    def test_a_rerun_converges_both_ways(self, paths: dict[str, Path]) -> None:
        assert self._main(paths, [closed_port()]) == 3
        assert paths["drop_in"].exists()

        with FakeDns() as dns:
            assert self._main(paths, [dns.server]) == 0
        assert paths["agent"].exists()
        assert not paths["drop_in"].exists()
        assert not paths["drop_in"].parent.exists()

        assert self._main(paths, [closed_port()]) == 3
        assert paths["drop_in"].exists()
        assert not paths["agent"].exists()

    def test_keeps_other_drop_ins(self, paths: dict[str, Path]) -> None:
        paths["drop_in"].parent.mkdir()
        other = paths["drop_in"].parent / "admin.conf"
        other.write_text("[Service]\n")

        with FakeDns() as dns:
            assert self._main(paths, [dns.server]) == 0

        assert other.exists()

    def test_a_missing_host_resolv_conf(self, paths: dict[str, Path]) -> None:
        paths["host"].unlink()

        assert self._main(paths, [closed_port()]) == 3
        assert _allowed(paths["drop_in"].read_text()) == []

    @pytest.mark.parametrize("bad", ["2606:4700::1111", "192.168.0.1", "bogus"])
    def test_refuses_a_public_resolver_the_agent_couldnt_reach(
        self, paths: dict[str, Path], bad: str
    ) -> None:
        assert self._main(paths, [bad]) == 2
        assert not paths["agent"].exists()
        assert not paths["drop_in"].exists()
